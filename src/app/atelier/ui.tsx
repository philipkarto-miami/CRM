type BadgeVariant = "success" | "accent" | "dark" | "outline" | "default" | "warning" | "error";

export function Badge({ variant = "default", dot, children }: { variant?: BadgeVariant; dot?: boolean; children: ReactNode }) {
  return (
    <span className={`af-badge af-badge--${variant}`}>
      {dot && <span className="af-badge__dot" aria-hidden />}
      {children}
    </span>
  );
}

/** Meme badge pour le statut d'une etape partout. */
export function StatusBadge({ status }: { status: StageViewStatus }) {
  switch (status) {
    case "done":
      return <Badge variant="success">Terminée</Badge>;
    case "running":
      return (
        <Badge variant="accent" dot>
          En cours
        </Badge>
      );
    case "paused":
      return (
        <Badge variant="warning" dot>
          En pause
        </Badge>
      );
    case "blocked":
      return <Badge variant="error">Bloquée</Badge>;
    case "ready":
      return <Badge variant="outline">Prête</Badge>;
    default:
      return <Badge variant="default">En attente</Badge>;
  }
}

export function Bar({
  value,
  color = "var(--ok)",
  track,
  height = 6,
  label,
}: {
  value: number;
  color?: string;
  track?: string;
  height?: number;
  label: string;
}) {
  const pct = Math.max(0, Math.min(100, Math.round(value * 100)));
  return (
    <div
      className="af-bar"
      style={{ height, background: track }}
      role="progressbar"
      aria-valuenow={pct}
      aria-valuemin={0}
      aria-valuemax={100}
      aria-label={label}
    >
      <span style={{ width: `${pct}%`, background: color }} />
    </div>
  );
}

