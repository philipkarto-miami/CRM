/** Fond de l'en-tete d'une carte etape selon son statut. */
export function headBg(status: StageViewStatus): string {
  if (status === "running" || status === "paused") return "var(--gold-xlight)";
  if (status === "waiting") return "var(--paper)";
  if (status === "done") return "#f1f8f4";
  return "var(--line-soft)";
}
