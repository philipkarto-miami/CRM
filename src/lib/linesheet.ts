export const LINE_SHEET_CODES: LineSheetCode[] = RAW.map(([sku, model, silhouette, size, color, execution, edition, cap]) => ({
  sku, model, silhouette, size, color, execution, edition, cap,
}));

export const LINE_SHEET_BY_SKU: Map<string, LineSheetCode> = new Map(LINE_SHEET_CODES.map((c) => [c.sku, c]));

// Codes du line sheet absents du catalogue (liste de codes du CRM).
export function missingLineSheetCodes(catalogSkus: Iterable<string>): LineSheetCode[] {
  const have = new Set(catalogSkus);
  return LINE_SHEET_CODES.filter((c) => !have.has(c.sku));
}

// Codes du catalogue qui ne figurent pas dans le line sheet (anciens codes,
// essais, archives...). Information, jamais une erreur.
export function codesOutsideLineSheet(catalogSkus: Iterable<string>): string[] {
  const out: string[] = [];
  for (const sku of catalogSkus) if (!LINE_SHEET_BY_SKU.has(sku)) out.push(sku);
  return out.sort();
}

// Pour un code manquant, un code du catalogue qui lui ressemble a un detail pres
// (marqueur Neverfull oublie : PKSQPG ~ PKNSQPG ; PKNF au lieu de PKN). A verifier
// par un humain : on ne renomme jamais tout seul.
export function lookalikeCode(sku: string, catalogSkus: Set<string>): string | null {
  const stem = sku.startsWith("PK") ? sku.slice(2) : sku;
  const candidates = [`PKN${stem}`, stem.startsWith("NF") ? `PKN${stem.slice(2)}` : "", stem.startsWith("N") ? `PK${stem.slice(1)}` : ""];
  return candidates.find((c) => c && c !== sku && catalogSkus.has(c)) ?? null;
}
