-- ============================================================================
-- Matrice des editions (lookbook : "Edition Matrix").
--  1. Table collection_designs : un design de la collection = nom, edition
--     commerciale (PK01..PK04), execution et modeles / tailles vendus. Editable
--     dans Reglages > Collection.
--  2. sku_catalog.design_name : le nom lisible du design (Square Painted) pose
--     sur chaque code ; c'est lui qui s'affiche a l'atelier au lieu de l'acronyme.
--  3. Remplissage des noms pour les codes du line sheet, puis edition commerciale
--     et execution recopiees de la matrice (la matrice fait foi).
-- Rejouable sans risque. A lancer apres 0035.
-- ============================================================================

-- 1. Table ---------------------------------------------------------------------
create table if not exists collection_designs (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  edition text not null,
  execution text,
  -- { "keepall": ["45","50","55"], "speedy": ["25","30"], "neverfull": ["PM"], "birkin": [...] }
  availability jsonb not null default '{}'::jsonb,
  sort_order integer not null default 999,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint collection_designs_execution_check
    check (execution is null or execution in (
      'hand_painted', 'hand_painted_embroidered', 'patch_mixed_media',
      'artwork', 'collector_hermes', 'limited_edition'
    ))
);

drop trigger if exists collection_designs_set_updated_at on collection_designs;
create trigger collection_designs_set_updated_at
  before update on collection_designs
  for each row execute procedure set_updated_at();

alter table collection_designs enable row level security;

drop policy if exists "collection_designs: lecture" on collection_designs;
create policy "collection_designs: lecture" on collection_designs
  for select using (auth.uid() is not null);

drop policy if exists "collection_designs: ecriture admin" on collection_designs;
create policy "collection_designs: ecriture admin" on collection_designs
  for all using (auth_role() = 'admin') with check (auth_role() = 'admin');

