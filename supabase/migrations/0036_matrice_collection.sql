-- Edition commerciale et execution des designs de la matrice : la matrice fait foi
-- pour l'edition ; l'execution n'est posee que si elle est encore vide.
update sku_catalog s
set
  commercial_edition = cd.edition,
  execution = coalesce(s.execution, cd.execution)
from collection_designs cd
where s.design_name = cd.name
  and (s.commercial_edition is distinct from cd.edition or (s.execution is null and cd.execution is not null));

